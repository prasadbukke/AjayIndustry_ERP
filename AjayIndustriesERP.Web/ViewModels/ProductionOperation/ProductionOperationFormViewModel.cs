File: ProductionOperationFormViewModel.cs

Purpose:
Provides Production Operation Master data to Create and Edit forms.

Responsibilities:
- Accept Operation Name.
- Accept Operation Type.
- Accept optional Description.
- Accept optional Remarks.
- Provide Web-level validation.
- Support both Create and Edit using reusable _Form.cshtml.

Important:
- Operation Code is generated by ProductionOperationService.
- Business validation remains in Application Service.
- Setup Time, Cycle Time and Machine assignment do NOT belong
  to Operation Master.
